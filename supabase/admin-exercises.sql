alter table public.exercises enable row level security;
alter table public.exercises
  add column if not exists exercise_number bigint generated by default as identity;

revoke select (exercise_number) on table public.exercises from public, anon, authenticated;
grant select (exercise_number) on table public.exercises to anon, authenticated;

create unique index if not exists exercises_exercise_number_key
on public.exercises (exercise_number);

revoke select on table public.exercises from public, anon, authenticated;
revoke select (correct_answer) on table public.exercises from public, anon, authenticated;
grant select (
  id,
  exercise_number,
  topic,
  chapter,
  grade,
  origin,
  prompt_text,
  additional_text,
  image_url,
  answer_type,
  options,
  created_at
) on table public.exercises to anon, authenticated;

revoke insert on table public.exercises from public, anon, authenticated;
revoke insert (
  topic,
  chapter,
  grade,
  origin,
  prompt_text,
  additional_text,
  image_url,
  answer_type,
  options,
  correct_answer
) on table public.exercises from public, anon, authenticated;
grant insert (
  topic,
  chapter,
  grade,
  origin,
  prompt_text,
  additional_text,
  image_url,
  answer_type,
  options,
  correct_answer
) on table public.exercises to authenticated;

drop policy if exists exercises_public_read on public.exercises;
create policy exercises_public_read
on public.exercises
for select
to anon, authenticated
using (true);

drop policy if exists exercises_admin_insert on public.exercises;
create policy exercises_admin_insert
on public.exercises
for insert
to authenticated
with check (true);

drop policy if exists exercises_admin_insert_guard on public.exercises;
create policy exercises_admin_insert_guard
on public.exercises
as restrictive
for insert
to authenticated
with check ((select public.is_admin()));

